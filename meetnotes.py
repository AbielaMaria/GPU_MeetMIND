def parrotlet_transcribe_fixed(
    model,
    audio,
    orig_sr,
    max_new_tokens=128,
    repetition_penalty=1.2,
):
    device = next(model.parameters()).device

    print("=" * 70)
    print("PARROTLET-A FIXED TRANSCRIPTION PIPELINE")
    print("=" * 70)

    # --------------------------------------------------------
    # 1. Original Parrotlet prompt
    # --------------------------------------------------------

    prompt = model.get_prompt()

    input_ids = torch.tensor(
        model.tokenizer(
            prompt,
            add_special_tokens=False
        )["input_ids"],
        dtype=torch.long,
        device=device
    ).unsqueeze(0)

    input_attention_mask = torch.ones_like(input_ids)

    # --------------------------------------------------------
    # 2. Locate audio token
    # --------------------------------------------------------

    audio_token = model.tokenizer.convert_tokens_to_ids(
        model.audio_token
    )

    audio_pos = input_ids[0].tolist().index(audio_token)

    print("Audio token position:", audio_pos)

    # --------------------------------------------------------
    # 3. Audio is ALREADY 16 kHz
    # --------------------------------------------------------

    processed_audio = audio

    print("Audio sample rate:", orig_sr)
    print("Audio samples:", len(processed_audio))

    # --------------------------------------------------------
    # 4. Feature extraction
    # --------------------------------------------------------

    audio_features = model.processor.feature_extractor(
        [processed_audio],
        sampling_rate=model.sampling_rate,
        return_tensors="pt"
    ).input_features

    # IMPORTANT:
    # Feature extractor produces float32.
    # Whisper encoder is BF16.
    # Convert HERE.
    encoder_dtype = model.encoder.conv1.weight.dtype

    audio_features = audio_features.to(
        device=device,
        dtype=encoder_dtype
    )

    print("Audio feature dtype:", audio_features.dtype)
    print("Encoder dtype:", encoder_dtype)

    # --------------------------------------------------------
    # 5. Whisper encoder
    # --------------------------------------------------------

    with torch.no_grad():
        audio_embeddings = model.encoder(
            audio_features
        ).last_hidden_state

    print("Encoder output:", audio_embeddings.shape)
    print("Encoder output dtype:", audio_embeddings.dtype)

    # --------------------------------------------------------
    # 6. Projector
    # --------------------------------------------------------

    projector_dtype = next(
        model.projector.parameters()
    ).dtype

    print("Projector dtype:", projector_dtype)

    audio_embeddings_projector = audio_embeddings.to(
        projector_dtype
    )

    with torch.no_grad():
        projected_audio_embeddings = model.projector(
            audio_embeddings_projector
        )

    print(
        "Projected audio:",
        projected_audio_embeddings.shape
    )
    print(
        "Projected audio dtype:",
        projected_audio_embeddings.dtype
    )

    # --------------------------------------------------------
    # 7. Decoder text embeddings
    # --------------------------------------------------------

    input_embeddings = model.decoder.get_input_embeddings()(
        input_ids
    )

    decoder_dtype = input_embeddings.dtype

    print("Decoder dtype:", decoder_dtype)

    projected_audio_embeddings = (
        projected_audio_embeddings.to(decoder_dtype)
    )

    # --------------------------------------------------------
    # 8. Combine text + audio embeddings
    # --------------------------------------------------------

    batch_size, input_seq_len, embed_dim = (
        input_embeddings.shape
    )

    audio_seq_len = projected_audio_embeddings.shape[1]

    combined_len = (
        input_seq_len +
        audio_seq_len -
        1
    )

    combined_embeddings = torch.zeros(
        batch_size,
        combined_len,
        embed_dim,
        device=device,
        dtype=decoder_dtype
    )

    combined_attention_mask = torch.zeros(
        batch_size,
        combined_len,
        device=device,
        dtype=torch.long
    )

    # Text before audio
    combined_embeddings[
        :, :audio_pos
    ] = input_embeddings[
        :, :audio_pos
    ]

    combined_attention_mask[
        :, :audio_pos
    ] = 1

    # Audio
    combined_embeddings[
        :,
        audio_pos:audio_pos + audio_seq_len
    ] = projected_audio_embeddings

    combined_attention_mask[
        :,
        audio_pos:audio_pos + audio_seq_len
    ] = 1

    # Text after audio
    suffix_start = audio_pos + 1
    suffix_len = input_seq_len - suffix_start
    out_start = audio_pos + audio_seq_len

    if suffix_len > 0:
        combined_embeddings[
            :,
            out_start:out_start + suffix_len
        ] = input_embeddings[
            :,
            suffix_start:
        ]

        combined_attention_mask[
            :,
            out_start:out_start + suffix_len
        ] = 1

    print()
    print("Combined embeddings:", combined_embeddings.shape)
    print("Combined dtype:", combined_embeddings.dtype)

    # --------------------------------------------------------
    # 9. IMPORTANT:
    # Use decoder.generate with the combined embeddings.
    #
    # We do NOT pass input_ids because Transformers 4.57
    # may reject inputs_embeds for this Gemma class.
    #
    # Instead, provide the embeddings through a custom
    # generation call using the decoder's forward method.
    # --------------------------------------------------------

    print()
    print("=" * 70)
    print("DECODER")
    print("=" * 70)

    # First verify that Gemma itself accepts inputs_embeds.
    with torch.no_grad():
        test_output = model.decoder(
            inputs_embeds=combined_embeddings,
            attention_mask=combined_attention_mask,
            use_cache=False
        )

    print("Decoder forward: SUCCESS")
    print("Logits shape:", test_output.logits.shape)

    return test_output


