def generate_parrotlet_transcript(
    model,
    combined_embeddings,
    combined_attention_mask,
    max_new_tokens=128,
    repetition_penalty=1.2,
):
    decoder = model.decoder
    tokenizer = model.tokenizer

    device = combined_embeddings.device

    print("=" * 70)
    print("PARROTLET-A 2.5 PRO — TOKEN GENERATION")
    print("=" * 70)

    # --------------------------------------------------------
    # First pass: process complete audio + prompt
    # --------------------------------------------------------

    print("Processing audio + prompt...")

    with torch.no_grad():
        outputs = decoder(
            inputs_embeds=combined_embeddings,
            attention_mask=combined_attention_mask,
            use_cache=True,
        )

    past_key_values = outputs.past_key_values

    # Last position predicts first transcript token
    logits = outputs.logits[:, -1, :].clone()

    generated_tokens = []

    # --------------------------------------------------------
    # Autoregressive generation
    # --------------------------------------------------------

    for step in range(max_new_tokens):

        # Repetition penalty
        if repetition_penalty != 1.0 and generated_tokens:

            for token_id in set(generated_tokens):

                if logits[0, token_id] < 0:
                    logits[0, token_id] *= repetition_penalty
                else:
                    logits[0, token_id] /= repetition_penalty

        # Greedy decoding
        next_token = torch.argmax(
            logits,
            dim=-1,
            keepdim=True,
        )

        token_id = next_token.item()

        generated_tokens.append(token_id)

        # EOS tokens from Parrotlet configuration
        if token_id in [1, 106]:
            print(
                "EOS reached at token:",
                step + 1
            )
            break

        # Show progress
        if (step + 1) % 10 == 0:

            partial_text = tokenizer.decode(
                generated_tokens,
                skip_special_tokens=True,
            )

            print(
                f"Tokens: {step + 1} | "
                f"Text: {partial_text}"
            )

        # ----------------------------------------------------
        # Convert new token to embedding
        # ----------------------------------------------------

        next_embedding = decoder.get_input_embeddings()(
            next_token
        )

        # ----------------------------------------------------
        # Extend attention mask
        # ----------------------------------------------------

        new_attention_mask = torch.cat(
            [
                combined_attention_mask,
                torch.ones(
                    (1, 1),
                    dtype=combined_attention_mask.dtype,
                    device=device,
                ),
            ],
            dim=1,
        )

        # ----------------------------------------------------
        # Process only newly generated token
        # ----------------------------------------------------

        with torch.no_grad():

            outputs = decoder(
                inputs_embeds=next_embedding,
                attention_mask=new_attention_mask,
                past_key_values=past_key_values,
                use_cache=True,
            )

        past_key_values = outputs.past_key_values

        logits = outputs.logits[:, -1, :].clone()

        combined_attention_mask = new_attention_mask

    # --------------------------------------------------------
    # Decode final tokens
    # --------------------------------------------------------

    transcript = tokenizer.decode(
        generated_tokens,
        skip_special_tokens=True,
    ).strip()

    return transcript, generated_tokens


